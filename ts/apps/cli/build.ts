// Builds the slopmax binary, `dist/slopmax`, and holds it to its budget.
//
//   bun build.ts compile   ahead of time, with Bun canary (`bun compile --trim`): the shipped build
//   bun build.ts build     without the ahead-of-time compiler (`--no-aot --minify --bytecode`): the
//                          fallback, for when AOT breaks a feature; its bytecode is laid out by
//                          profiles of `--version`, `status --json` and `serve`, recorded on a first build
//   bun build.ts budget    fails when dist/slopmax is over 70 MiB (26 MB as xz), or carries a
//                          third-party package beyond the ones ARCHITECTURE.md §14 lists
//
// Both builds first build the web UI (apps/ui) and write `src/embedded.ts`,
// which lists its files so the binary carries them; the checked-in stub,
// which carries none, is put back afterwards whatever happens. The compiler
// is the Bun running this script: the `compile` mise task runs it on canary.
import { Platform } from "@slopmax/core"
import { Cause, Data, Effect, Exit, FileSystem, Path, Schedule, Schema, Stream } from "effect"
import { Command, Flag } from "effect/cli"
import { ChildProcess, ChildProcessSpawner } from "effect/process"

const root = import.meta.dir
const dist = `${root}/dist`
const binary = `${dist}/slopmax`
const metafile = `${dist}/slopmax.meta.json`
const ui = `${root}/../ui`
const web = `${ui}/dist/web`
const embeddedFile = `${root}/src/embedded.ts`
const entry = `${root}/src/main.ts`

/** The budget of ARCHITECTURE.md §16. */
export const sizeBudget = 70 * 1024 * 1024
export const xzBudget = 26_000_000

/** The only third-party packages the binary may carry (ARCHITECTURE.md §14). */
export const allowedPackages: ReadonlyArray<string> = [
  "effect",
  "@effect/platform-bun",
  "@effect/platform-node-shared",
  "ws",
  "@decimalturn/toml-patch",
]

/** Flags both builds share: a stray `.env`, bunfig, tsconfig or package.json beside the binary changes nothing. */
const noAutoload = [
  "--no-compile-autoload-dotenv",
  "--no-compile-autoload-bunfig",
  "--no-compile-autoload-tsconfig",
  "--no-compile-autoload-package-json",
]

/**
 * The ahead-of-time build. `--trim` drops the Bun and Node APIs slopmax never
 * calls; `--trim-locales=en` keeps only English locale data (every format
 * slopmax writes is en-US); `--no-compile-function-source` leaves out the
 * functions' source text, which nothing reads (no `eval`, no `toString`).
 */
export const aotArgs = (outfile: string, explain: boolean): ReadonlyArray<string> => [
  "compile",
  "--no-script",
  "--trim",
  "--trim-locales=en",
  "--no-compile-function-source",
  ...noAutoload,
  ...(explain ? ["--explain=text"] : []),
  `--metafile=${metafile}`,
  `--outfile=${outfile}`,
  entry,
]

/**
 * The fallback build: bytecode (the one large lever on startup), laid out
 * by the profiles when there are some, and the JIT held back during start
 * (the daemon lets it go once it listens).
 */
export const fallbackArgs = (outfile: string, profiles: ReadonlyArray<string>): ReadonlyArray<string> => [
  "build",
  "--compile",
  "--no-aot",
  "--minify",
  "--bytecode",
  "--format=esm",
  "--compile-jit-policy=4",
  ...noAutoload,
  ...(profiles.length > 0 ? [`--bytecode-order=${profiles.join(",")}`] : []),
  `--metafile=${metafile}`,
  `--outfile=${outfile}`,
  entry,
]

/** A file's import name in `embedded.ts`. */
const binding = (index: number) => `file${index}`

/**
 * `embedded.ts` for the web build's files (names relative to it, compressed
 * copies included): each file as brotli and gzip when it has them, else as
 * it is (fonts are compressed already). The server unzips the gzip copy
 * when a browser takes neither.
 */
export const embeddedSource = (names: ReadonlyArray<string>, from: string): string => {
  const present = new Set(names)
  const originals = names.filter((name) => !name.endsWith(".br") && !name.endsWith(".gz")).toSorted()
  const imports: Array<string> = []
  const entries: Array<string> = []
  let index = 0
  const take = (file: string) => {
    const name = binding(index)
    index += 1
    imports.push(`import ${name} from ${JSON.stringify(`${from}/${file}`)} with { type: "file" }`)
    return `Bun.file(${name})`
  }
  for (const name of originals) {
    const compressed = present.has(`${name}.br`) || present.has(`${name}.gz`)
    const parts = compressed
      ? [
          ...(present.has(`${name}.br`) ? [`br: ${take(`${name}.br`)}`] : []),
          ...(present.has(`${name}.gz`) ? [`gzip: ${take(`${name}.gz`)}`] : []),
        ]
      : [`plain: ${take(name)}`]
    entries.push(`  ${JSON.stringify(name)}: { ${parts.join(", ")} },`)
  }
  return [
    "// Generated by build.ts for the build; the checked-in stub carries no files.",
    'import { Assets } from "@slopmax/core"',
    'import type { Layer } from "effect"',
    ...imports,
    "",
    "export const embedded: Layer.Layer<Assets> = Assets.layerFiles({",
    ...entries,
    "})",
    "",
  ].join("\n")
}

/** A program the build ran failed. */
class StepFailed extends Data.TaggedError("StepFailed")<{ readonly step: string; readonly code: number }> {
  override get message(): string {
    return `${this.step} failed (exit ${this.code})`
  }
}

/** Over budget, or carrying a package it should not. */
class OverBudget extends Data.TaggedError("OverBudget")<{ readonly problems: ReadonlyArray<string> }> {
  override get message(): string {
    return this.problems.join("\n")
  }
}

/** Runs a program with this terminal, failing unless it exits 0. */
const exec = (step: string, program: string, args: ReadonlyArray<string>, env: Record<string, string> = {}) =>
  Effect.scoped(
    Effect.gen(function* () {
      const spawner = yield* ChildProcessSpawner.ChildProcessSpawner
      const handle = yield* spawner.spawn(
        ChildProcess.make(program, args, {
          cwd: root,
          env,
          extendEnv: true,
          stdin: "ignore",
          stdout: "inherit",
          stderr: "inherit",
        }),
      )
      const code = Number(yield* handle.exitCode)
      if (code !== 0) return yield* new StepFailed({ step, code })
    }),
  )

const bun = process.execPath

/** The files under `dir`, by name relative to it; its folders are not files to serve. */
export const filesUnder = (dir: string) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem
    const path = yield* Path.Path
    const names = yield* fs.readDirectory(dir, { recursive: true })
    return yield* Effect.filter(names, (name) =>
      Effect.map(fs.stat(path.join(dir, name)), (info) => info.type === "File"),
    )
  })

/** Builds the web UI and lists its files into `embedded.ts` for as long as `body` runs. */
const withEmbedded = <A, E, R>(body: Effect.Effect<A, E, R>) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem
    const path = yield* Path.Path
    yield* exec("the web UI's build", bun, ["run", "--cwd", ui, "build"])
    const names = yield* filesUnder(web)
    const stub = yield* fs.readFileString(embeddedFile)
    const from = path.relative(path.dirname(embeddedFile), web)
    return yield* Effect.acquireUseRelease(
      fs.writeFileString(embeddedFile, embeddedSource(names, from)),
      () => body,
      () => Effect.orDie(fs.writeFileString(embeddedFile, stub)),
    )
  })

/** A port nothing listens on, for the profiling run of `serve` and the CLI's sandboxes. */
export const freePort = Effect.sync(() => {
  const listener = Bun.listen({ hostname: "127.0.0.1", port: 0, socket: { data() {} } })
  const port = listener.port
  listener.stop(true)
  return port
})

/**
 * Records which functions `--version`, `status --json` and `serve` run, in
 * a throwaway home, so the second build lays the bytecode out in that order.
 */
const recordProfiles = (outfile: string) =>
  Effect.scoped(
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem
      const spawner = yield* ChildProcessSpawner.ChildProcessSpawner
      const home = yield* fs.makeTempDirectoryScoped({ prefix: "slopmax-profile-" })
      const port = yield* freePort
      const env = {
        HOME: home,
        SLOPMAX_HOME: `${home}/.slopmax`,
        CLAUDE_CONFIG_DIR: `${home}/.claude`,
        CODEX_HOME: `${home}/.codex`,
        XDG_CONFIG_HOME: `${home}/.config`,
        SLOPMAX_LISTEN: `127.0.0.1:${port}`,
        SLOPMAX_NO_SERVICE: "1",
        SLOPMAX_CLIPROXYAPI_PORT: "9",
        HTTPS_PROXY: "http://127.0.0.1:9",
      }
      const profile = (name: string) => `${home}/${name}.order`
      yield* exec("profiling --version", outfile, ["--version"], { ...env, BUN_BYTECODE_ORDER_OUT: profile("version") })
      yield* exec("profiling status", outfile, ["status", "--json"], {
        ...env,
        BUN_BYTECODE_ORDER_OUT: profile("status"),
      })
      yield* Effect.scoped(
        Effect.gen(function* () {
          const serve = yield* spawner.spawn(
            ChildProcess.make(outfile, ["serve"], {
              env: { ...env, BUN_BYTECODE_ORDER_OUT: profile("serve") },
              extendEnv: true,
              stdin: "ignore",
              stdout: "ignore",
              stderr: "ignore",
            }),
          )
          yield* Effect.tryPromise(() => fetch(`http://127.0.0.1:${port}/healthz`)).pipe(
            Effect.retry({ times: 100, schedule: Schedule.spaced("50 millis") }),
          )
          yield* exec("stopping the profiled serve", outfile, ["stop"], env)
          yield* serve.exitCode
        }),
      )
      // Kept beside the binary, so a rebuild can use them without profiling again.
      const kept: Array<string> = []
      for (const name of ["version", "serve", "status"]) {
        const target = `${dist}/${name}.order`
        if (yield* fs.exists(profile(name))) {
          yield* fs.copyFile(profile(name), target)
          kept.push(target)
        }
      }
      return kept
    }),
  )

const compile = Command.make(
  "compile",
  {
    explain: Flag.Boolean("explain").pipe(
      Flag.withDescription("List the code that compiled to a slow path, worst first"),
      Flag.withDefault(false),
    ),
  },
  ({ explain }) =>
    Effect.gen(function* () {
      yield* (yield* FileSystem.FileSystem).makeDirectory(dist, { recursive: true })
      yield* withEmbedded(exec("bun compile", bun, aotArgs(binary, explain)))
    }),
).pipe(Command.withDescription("Build dist/slopmax ahead of time (Bun canary)"))

const build = Command.make("build", {}, () =>
  Effect.gen(function* () {
    yield* (yield* FileSystem.FileSystem).makeDirectory(dist, { recursive: true })
    yield* withEmbedded(
      Effect.gen(function* () {
        yield* exec("bun build --compile", bun, fallbackArgs(binary, []))
        const profiles = yield* recordProfiles(binary)
        yield* exec("bun build --compile (ordered)", bun, fallbackArgs(binary, profiles))
      }),
    )
  }),
).pipe(Command.withDescription("Build dist/slopmax without the ahead-of-time compiler, the fallback"))

const Metafile = Schema.Struct({ inputs: Schema.Record(Schema.String, Schema.Unknown) })

/** The third-party packages a bundle's inputs come from. */
export const packagesOf = (inputs: ReadonlyArray<string>): ReadonlyArray<string> => {
  const found = new Set<string>()
  for (const input of inputs) {
    const at = input.lastIndexOf("node_modules/")
    if (at < 0) continue
    const [scope = "", name = ""] = input.slice(at + "node_modules/".length).split("/")
    const pkg = scope.startsWith("@") ? `${scope}/${name}` : scope
    if (!pkg.startsWith("@slopmax/")) found.add(pkg)
  }
  return [...found].toSorted()
}

/** What is over budget, if anything. */
export const budgetProblems = (
  bytes: number,
  xzBytes: number,
  packages: ReadonlyArray<string>,
): ReadonlyArray<string> => [
  ...(bytes > sizeBudget ? [`dist/slopmax is ${bytes} bytes (budget ${sizeBudget})`] : []),
  ...(xzBytes > xzBudget ? [`dist/slopmax is ${xzBytes} bytes as xz (budget ${xzBudget})`] : []),
  ...packages
    .filter((pkg) => !allowedPackages.includes(pkg))
    .map((pkg) => `dist/slopmax carries ${pkg}, which ARCHITECTURE.md §14 does not list`),
]

const budget = Command.make("budget", {}, () =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem
    const spawner = yield* ChildProcessSpawner.ChildProcessSpawner
    const bytes = Number((yield* fs.stat(binary)).size)
    const xzBytes = yield* Effect.scoped(
      Effect.gen(function* () {
        const xz = yield* spawner.spawn(
          ChildProcess.make("xz", ["-9", "-T0", "-c", binary], { stdin: "ignore", stderr: "inherit" }),
        )
        return yield* xz.stdout.pipe(
          Stream.runFold(
            () => 0,
            (total, chunk: Uint8Array) => total + chunk.length,
          ),
        )
      }),
    )
    const meta = yield* fs
      .readFileString(metafile)
      .pipe(Effect.flatMap(Schema.decodeUnknownEffect(Schema.fromJsonString(Metafile))))
    const packages = packagesOf(Object.keys(meta.inputs))
    yield* Effect.log(
      `dist/slopmax: ${bytes} bytes (budget ${sizeBudget}), ${xzBytes} as xz (budget ${xzBudget}); packages: ${packages.join(", ")}`,
    )
    const problems = budgetProblems(bytes, xzBytes, packages)
    if (problems.length > 0) return yield* new OverBudget({ problems })
  }),
).pipe(Command.withDescription("Hold dist/slopmax to its size budget and its package list"))

const cli = Command.make("build.ts").pipe(Command.withSubcommands([compile, build, budget]))

if (import.meta.main) {
  const exit = await Effect.runPromiseExit(Command.run(cli, { version: "1" }).pipe(Effect.provide(Platform.layer)))
  if (Exit.isFailure(exit)) {
    const failure = exit.cause.reasons.find(Cause.isFailReason)
    console.error(
      failure !== undefined && failure.error instanceof Error ? failure.error.message : Cause.pretty(exit.cause),
    )
    process.exitCode = 1
  }
}
